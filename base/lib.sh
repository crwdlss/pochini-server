#!/bin/bash
# Общие функции для check.sh

ok()   { echo -e "\e[32m✅ $*\e[0m"; }
fail() { echo -e "\e[31m❌ $*\e[0m"; exit 1; }
info() { echo -e "\e[36m…  $*\e[0m"; }

solved() {
    echo
    echo -e "\e[1;32m🎉 Задача решена!\e[0m"
    echo "Теперь объясни себе вслух: что сломалось, как ты это нашёл и как исправил."
    echo "Именно так это спросят на собеседовании."
}
